c.CustomerName,
COUNT(r.ReturnID) AS Returns
FROM customers c
JOIN orders o
ON c.CustomerID=o.CustomerID
JOIN returns r
ON o.OrderID=r.OrderID
GROUP BY c.CustomerName
ORDER BY Returns DESC;

