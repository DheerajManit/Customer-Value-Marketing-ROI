------------------------------------------------------------
-- 29. Customers without Returns
------------------------------------------------------------

SELECT DISTINCT
c.CustomerID,
c.CustomerName
FROM customers c
JOIN orders o
ON c.CustomerID=o.CustomerID
LEFT JOIN returns r
ON o.OrderID=r.OrderID
WHERE r.ReturnID IS NULL;

------------------------------------------------------------
-- 30. Customers with Highest Number of Returns
------------------------------------------------------------

