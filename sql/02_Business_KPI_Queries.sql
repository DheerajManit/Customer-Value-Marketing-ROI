

USE ecommerce_analytics;

------------------------------------------------------------
-- 1. Top 10 Customers by Revenue
------------------------------------------------------------  

SELECT
    c.CustomerID,
    c.CustomerName,
    ROUND(SUM(o.TotalAmount),2) AS Revenue
FROM customers c
JOIN orders o
ON c.CustomerID = o.CustomerID
GROUP BY c.CustomerID,c.CustomerName
ORDER BY Revenue DESC
LIMIT 10;

------------------------------------------------------------
-- 2. Top 10 Selling Products
------------------------------------------------------------

SELECT
    p.ProductName,
    SUM(o.Quantity) AS QuantitySold
FROM products p
JOIN orders o
ON p.ProductID=o.ProductID
GROUP BY p.ProductName
ORDER BY QuantitySold DESC
LIMIT 10;

------------------------------------------------------------
-- 3. Revenue Generated by Each Product
------------------------------------------------------------

SELECT
    p.ProductName,
    ROUND(SUM(o.TotalAmount),2) AS Revenue
FROM products p
JOIN orders o
ON p.ProductID=o.ProductID
GROUP BY p.ProductName
ORDER BY Revenue DESC;

------------------------------------------------------------
-- 4. Revenue by Product Category
------------------------------------------------------------

SELECT
    p.Category,
    ROUND(SUM(o.TotalAmount),2) AS Revenue
FROM products p
JOIN orders o
ON p.ProductID=o.ProductID
GROUP BY p.Category
ORDER BY Revenue DESC;

------------------------------------------------------------
-- 5. Average Order Value
------------------------------------------------------------

SELECT
ROUND(AVG(TotalAmount),2) AS AverageOrderValue
FROM orders;

------------------------------------------------------------
-- 6. Total Revenue
------------------------------------------------------------

SELECT
ROUND(SUM(TotalAmount),2) AS TotalRevenue
FROM orders;

------------------------------------------------------------
-- 7. Total Revenue by Region
------------------------------------------------------------

SELECT
    c.Region,
    ROUND(SUM(o.TotalAmount),2) AS Revenue
FROM customers c
JOIN orders o
ON c.CustomerID=o.CustomerID
GROUP BY c.Region
ORDER BY Revenue DESC;

------------------------------------------------------------
-- 8. Revenue by City
------------------------------------------------------------

SELECT
    c.City,
    ROUND(SUM(o.TotalAmount),2) AS Revenue
FROM customers c
JOIN orders o
ON c.CustomerID=o.CustomerID
GROUP BY c.City
ORDER BY Revenue DESC;

------------------------------------------------------------
-- 9. Monthly Sales Trend
------------------------------------------------------------

SELECT
    MONTH(OrderDate) AS MonthNumber,
    ROUND(SUM(TotalAmount),2) AS Revenue
FROM orders
GROUP BY MONTH(OrderDate)
ORDER BY MonthNumber;

------------------------------------------------------------
-- 10. Orders by Status
------------------------------------------------------------

SELECT
    OrderStatus,
    COUNT(*) AS Orders
FROM orders
GROUP BY OrderStatus;

------------------------------------------------------------
-- 11. Average Quantity Purchased
------------------------------------------------------------

SELECT
ROUND(AVG(Quantity),2) AS AverageQuantity
FROM orders;

------------------------------------------------------------
-- 12. Customer Lifetime Value
------------------------------------------------------------

SELECT
    c.CustomerID,
    c.CustomerName,
    COUNT(o.OrderID) AS OrdersPlaced,
    ROUND(SUM(o.TotalAmount),2) AS CustomerLifetimeValue
FROM customers c
JOIN orders o
ON c.CustomerID=o.CustomerID
GROUP BY c.CustomerID,c.CustomerName
ORDER BY CustomerLifetimeValue DESC;

------------------------------------------------------------
-- 13. Repeat Customers
------------------------------------------------------------

SELECT
    CustomerID,
    COUNT(OrderID) AS OrdersPlaced
FROM orders
GROUP BY CustomerID
HAVING COUNT(OrderID)>1
ORDER BY OrdersPlaced DESC;

------------------------------------------------------------
-- 14. Revenue by Gender
------------------------------------------------------------

SELECT
    c.Gender,
    ROUND(SUM(o.TotalAmount),2) AS Revenue
FROM customers c
JOIN orders o
ON c.CustomerID=o.CustomerID
GROUP BY c.Gender;

------------------------------------------------------------
-- 15. Revenue by Age Group
------------------------------------------------------------

SELECT
CASE
WHEN Age<25 THEN '18-24'
WHEN Age BETWEEN 25 AND 34 THEN '25-34'
WHEN Age BETWEEN 35 AND 44 THEN '35-44'
ELSE '45+'
END AS AgeGroup,
ROUND(SUM(o.TotalAmount),2) AS Revenue
FROM customers c
JOIN orders o
ON c.CustomerID=o.CustomerID
GROUP BY AgeGroup
ORDER BY Revenue DESC;

------------------------------------------------------------
-- 16. Campaign Performance
------------------------------------------------------------

SELECT
    ca.CampaignName,
    COUNT(o.OrderID) AS OrdersGenerated,
    ROUND(SUM(o.TotalAmount),2) AS Revenue
FROM campaigns ca
JOIN orders o
ON ca.CampaignID=o.CampaignID
GROUP BY ca.CampaignName
ORDER BY Revenue DESC;

------------------------------------------------------------
-- 17. Marketing ROI
------------------------------------------------------------

SELECT
    CampaignName,
    Budget,
    RevenueGenerated,
    ROUND(((RevenueGenerated-Budget)/Budget)*100,2) AS ROI_Percentage
FROM campaigns
ORDER BY ROI_Percentage DESC;

------------------------------------------------------------
-- 18. Highest Rated Products
------------------------------------------------------------

SELECT
    p.ProductName,
    ROUND(AVG(r.Rating),2) AS AverageRating
FROM products p
JOIN reviews r
ON p.ProductID=r.ProductID
GROUP BY p.ProductName
ORDER BY AverageRating DESC;

------------------------------------------------------------
-- 19. Review Distribution
------------------------------------------------------------

